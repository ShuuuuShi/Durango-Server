    /// <summary>tag ของไอเทมชิ้นนี้ (ไม่รู้จัก = ไม่มี tag เลย ไม่ใช่ null)</summary>
    public static Tag[] For(string prototype)
    {
        if (prototype != null && Map.TryGetValue(prototype, out Tag[] tags))
        {
            return tags;
        }
        return System.Array.Empty<Tag>();
    }

    /// <summary>
    /// สูตรที่คราฟต์ออกมาแล้วได้ของที่มี tag นี้ — ใช้ตอบ `ToolNeeded`
    /// (client เอา id ไปเปิดหน้าสูตรให้เลย ผู้เล่นจะได้รู้ว่าต้องคราฟต์อะไรถึงจะเก็บของนี้ได้)
    /// คิดครั้งเดียวแล้วจำไว้ เพราะวนทั้ง 1,900 prototype ทุกครั้งที่ขาดเครื่องมือมันเปลือง
    /// </summary>
    private static readonly Dictionary<string, string[]> _recipeCache = new Dictionary<string, string[]>();

    public static string[] RecipesMakingTag(string tag)
    {
        if (string.IsNullOrEmpty(tag))
        {
            return System.Array.Empty<string>();
        }
        lock (_recipeCache)
        {
            if (_recipeCache.TryGetValue(tag, out string[] cached))
            {
                return cached;
            }
            var found = new List<string>();
            foreach (KeyValuePair<string, Tag[]> pair in Map)
            {
                if (!RecipeRequirements.Recipes.ContainsKey(pair.Key))
                {
                    continue;                       // คราฟต์ไม่ได้ก็ไม่ต้องแนะนำ
                }
                for (int i = 0; i < pair.Value.Length; i++)
                {
                    if (pair.Value[i].Id == tag)
                    {
                        found.Add(pair.Key);
                        break;
                    }
                }
            }
            string[] result = found.ToArray();
            _recipeCache[tag] = result;
            return result;
        }
    }

    /// <summary>ไอเทมชิ้นนี้มี tag นี้ระดับเท่าไร (0 = ไม่มี)</summary>
    public static int LevelOf(string prototype, string tag)
    {
        Tag[] tags = For(prototype);
        for (int i = 0; i < tags.Length; i++)
        {
            if (tags[i].Id == tag)
            {
                return tags[i].Level;
            }
        }
        return 0;
    }
