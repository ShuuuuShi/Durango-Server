    public static string NameOf(string prototype, string fallback = null)
    {
        if (!string.IsNullOrEmpty(prototype) && Map.TryGetValue(prototype, out var row) && !string.IsNullOrEmpty(row.Name))
        {
            return row.Name;
        }
        return fallback ?? prototype;
    }

